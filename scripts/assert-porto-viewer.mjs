const projection=sql.slice(sql.indexOf('create or replace function public.porto_operational_overview'));
assert.ok(!/\b(charges|payments|scholarship_status|pricing_plan_id|custom_scholarship_amount|app_settings)\b/.test(projection));
assert.ok(!/\b(insert into|update public|delete from)\b/.test(projection));
assert.ok(sql.includes('as restrictive for all'));
assert.ok(sql.includes('porto_cannot_combine_staff_roles'));
assert.ok(sql.includes('finance_role_required'));
const printer=fs.readFileSync('src/app/api/sign-qz/route.ts','utf8');
assert.ok(printer.indexOf('!context.hasOperationalAccess') < printer.indexOf('process.env.QZ_PRIVATE_KEY'));
console.log('Porto input, projection and authorization source checks passed.');
