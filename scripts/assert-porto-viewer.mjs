import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PORTO_VIEWS, parsePortoPage, parsePortoView } from '../src/lib/auth/porto-viewer.ts';
assert.equal(Object.keys(PORTO_VIEWS).length, 8);
